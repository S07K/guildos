test('manual canvas draws and persists a layer without a provider key', async ({ page }) => {
 await page.setViewportSize({ width: 1440, height: 1000 });
 await page.goto('/signin');
 await page.getByLabel('Email address').fill('studio-test@example.com');
 await page.getByRole('button', { name: 'Send sign-in code' }).click();
 await page.getByLabel('Email code').fill('123456');
 await page.getByRole('button', { name: 'Enter your studio' }).click();
 await page.getByRole('link', { name: 'New project', exact: true }).click();
 await page.getByLabel('Project name').fill('Manual studio');
 await page.getByLabel('Your creative brief').fill('A manually designed landing page for independent designers.');
 await page.getByLabel('Primary button destination').fill('https://example.com');
 await page.getByRole('button', { name: 'Create project', exact: true }).click();
 await expect(page.getByText('No layers yet. Start a blank canvas or generate a first draft.')).toBeVisible();
 await page.getByRole('button', { name: 'Rectangle tool', exact: true }).click();
 const canvas = page.getByTestId('manual-canvas');
 const box = await canvas.boundingBox();
 const viewport = await page.getByRole('region', { name: 'Design canvas' }).boundingBox();
 expect(box).not.toBeNull(); expect(viewport).not.toBeNull();
 const left = Math.max(box!.x, viewport!.x), top = Math.max(box!.y, viewport!.y);
 const visibleWidth = Math.min(box!.x + box!.width, viewport!.x + viewport!.width) - left;
 const visibleHeight = Math.min(box!.y + box!.height, viewport!.y + viewport!.height) - top;
 const startX = left + Math.min(80, visibleWidth / 3), startY = top + Math.min(80, visibleHeight / 3);
 await page.mouse.move(startX, startY); await page.mouse.down();
 await page.mouse.move(startX + 200, startY + 110, { steps: 5 }); await page.mouse.up();
 await expect(canvas.locator('svg rect[data-node-id]')).toHaveCount(1);
 await page.getByLabel('Layer name').fill('Hero panel');
 await page.getByRole('button', { name: 'Project actions' }).click();
 await page.getByRole('menuitem', { name: 'Save changes' }).click();
 await expect(page.getByText('Unsaved', { exact: true })).toHaveCount(0);
 await page.reload();
 await expect(page.getByTestId('manual-canvas').locator('svg rect[data-node-id]')).toHaveCount(1);
 const savedShape = await page.getByTestId('manual-canvas').locator('svg rect[data-node-id]').boundingBox();
 expect(savedShape).not.toBeNull();
 await page.mouse.click(savedShape!.x + savedShape!.width / 2, savedShape!.y + savedShape!.height / 2);
 await expect(page.getByLabel('Layer name')).toHaveValue('Hero panel');
});
